"""Generate deliberate integrated-test placements from recovered component geometry.
These probe mechanism/audio/render cost; they are not claims of legal player routes.
"""
from pathlib import Path
import json,math
r=Path(__file__).resolve().parents[2]
j=json.loads((r/'wireframe/recovered-table.json').read_text())
edges=[e for e in j['edges']if e['class']not in ('5TDemo','8TBlocker')]
plan=[(7000,454,1),(7060,456,0),(7120,458,0),(7180,505,0),
 (7600,460,1),(7660,462,0),(7720,464,0),(7780,507,0),
 (8200,520,1),(8260,521,0),(8320,522,0),
 (8600,528,1),(8660,529,0),(8720,530,0),
 (9000,342,1),(9500,338,1),(10000,340,1),
 (10500,514,1),(10900,512,1)]
rows=[]
for tick,group,reset in plan:
 candidates=[e for e in edges if e['component']==group and e['active']]
 lines=[e for e in candidates if 'line'in e]
 e=max(lines,key=lambda e:math.hypot(e['line'][2]-e['line'][0],e['line'][3]-e['line'][1]))if lines else candidates[0]
 if 'line'in e:
  x,y,ex,ey=e['line'];ln=math.hypot(ex-x,ey-y);nx=(ey-y)/ln;ny=(x-ex)/ln
  x=(x+ex)/2+nx/16;y=(y+ey)/2+ny/16
  vx=-nx*15;vy=-ny*15
 else:x,y,_=e['circle'];vx=vy=0
 if group in (505,507):x-=60/256
 vals=[tick,round(x*256),round(y*256),round(vx*256),round(vy*256),e['mask'],reset]
 rows.append((vals,group,e['class']))
text=['/* Generated by verify_milestone_inputs.py; deliberate cost fixtures after frame7000. */',
 '#ifndef CADET_MILESTONE_INPUT_H','#define CADET_MILESTONE_INPUT_H',
 f'#define MILESTONE_FIRST_TICK {rows[0][0][0]}',
 'typedef struct {uint16_t tick;int16_t x,y,vx,vy;uint8_t mask,reset;} MilestonePlacement;',
 'static const MilestonePlacement milestone_placements[] __attribute__((section(".physics.rodata")))={']
for vals,group,kind in rows:text.append(' {'+','.join(map(str,vals))+'}, /* '+str(group)+' '+kind+' */')
text+=['};','static uint8_t milestone_placement_index;',
 '/* The test loop selects physics bank 62 around this call. */',
 'static __attribute__((section(".physics"),noinline)) void milestone_setup(uint16_t tick){',
 ' if(milestone_placement_index>=sizeof(milestone_placements)/sizeof(milestone_placements[0]))return;',
 ' const MilestonePlacement*p=milestone_placements+milestone_placement_index;',
 ' if(tick!=p->tick)return;',
 ' if(p->reset)game_start();',
 ' game_place(p->x,p->y,p->vx,p->vy,p->mask);',
 ' game.z=p->mask==4?350:77;',
 ' ++milestone_placement_index;',
 '}','#endif']
(r/'cadet/game/verify_milestone_input.h').write_text('\n'.join(text)+'\n')
print('Generated',len(rows),'deliberate placements in frames7000..10900')
